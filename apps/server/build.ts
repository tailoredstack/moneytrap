// Builds the single binary: the Vite web app, a generated manifest that embeds its files, then `bun build --compile`.
// Run: bun apps/server/build.ts   (output: dist/moneytrap)
// Pass --manifest-only to regenerate the manifest from whatever is already in apps/web/dist, for typecheck.

import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";

const serverDir = import.meta.dir;
const repo = resolve(serverDir, "../..");
const webDir = resolve(repo, "apps/web");
const webDist = join(webDir, "dist");
const manifestPath = join(serverDir, "src/web-assets.generated.ts");
const outfile = join(repo, "dist/moneytrap");

function run(command: string[], cwd: string, label: string): void {
  const result = Bun.spawnSync(command, { cwd, stdout: "inherit", stderr: "inherit" });
  if (result.exitCode !== 0) throw new Error(`${label} failed with exit code ${result.exitCode}`);
}

// Each built file gets one static import with `type: "file"`, which is how Bun embeds a file in a compiled binary.
async function writeManifest(): Promise<number> {
  const files: string[] = [];
  if (existsSync(webDist)) {
    for await (const file of new Bun.Glob("**/*").scan({ cwd: webDist, onlyFiles: true })) files.push(file);
  }
  files.sort();

  const imports: string[] = [];
  const entries: string[] = [];
  files.forEach((file, index) => {
    const fromManifest = relative(dirname(manifestPath), join(webDist, file)).split(sep).join("/");
    const specifier = fromManifest.startsWith(".") ? fromManifest : `./${fromManifest}`;
    imports.push(`import file${index} from ${JSON.stringify(specifier)} with { type: "file" };`);
    entries.push(`  ${JSON.stringify(`/${file}`)}: embeddedPath(file${index}),`);
    if (file === "index.html") entries.push(`  "/": embeddedPath(file${index}),`);
  });

  const source = [
    "// Generated by apps/server/build.ts. Do not edit; this file is gitignored.",
    ...imports,
    "",
    "// Bun types an imported .html file as an HTML bundle. At runtime it is the embedded file's path.",
    "const embeddedPath = (file: unknown): string => file as string;",
    "",
    "export const webAssets: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
  await writeFile(manifestPath, source);
  return files.length;
}

const manifestOnly = process.argv.includes("--manifest-only");
if (!manifestOnly) run([process.execPath, "run", "build"], webDir, "web build");

const embedded = await writeManifest();
console.log(`embedded ${embedded} web file(s)`);

if (!manifestOnly) {
  await mkdir(dirname(outfile), { recursive: true });
  run(
    [process.execPath, "build", "--compile", join(serverDir, "src/index.ts"), "--outfile", outfile],
    repo,
    "binary build",
  );
  console.log(`built ${outfile}`);
}
